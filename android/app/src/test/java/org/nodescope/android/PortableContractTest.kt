package org.nodescope.android

import java.io.File
import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.builtins.serializer
import kotlinx.serialization.json.*
import org.junit.Assert.*
import org.junit.Test
import org.nodescope.android.feature.candidatesites.PortableInputFingerprint
import org.nodescope.android.feature.candidatesites.SavedAntenna
import org.nodescope.android.feature.candidatesites.SavedEndpoint
import org.nodescope.android.feature.candidatesites.SavedLinkProfile
import org.nodescope.android.feature.coverage.*

/**
 * Saved-plans v3 contract gate: Kotlin must reproduce the shared vectors exactly. The same file is
 * checked by iOS's PortableContractTests, and both are generated by an independent Python reference.
 */
class PortableContractTest {
    private val vectors = Json.parseToJsonElement(File("../../shared/fixtures/saved-plans/contract-vectors-v1.json").readText()).jsonObject
    private fun JsonElement.double() = java.lang.Double.longBitsToDouble(java.lang.Long.parseUnsignedLong(jsonPrimitive.content.removePrefix("0x"), 16))
    private fun Double.bits() = "0x%016x".format(toRawBits())
    private fun JsonObject.d(name: String) = getValue(name).double()

    @Test fun coverageFingerprintsMatchTheReference() {
        val cases = vectors.getValue("coverageInputs").jsonArray
        assertEquals(9, cases.size)
        for (case in cases.map { it.jsonObject }) {
            val input = case.getValue("input").jsonObject
            val doubles = listOf("transmitterLatitude", "transmitterLongitude", "frequencyMHz", "transmitHeightMeters",
                "receiveHeightMeters", "transmitPowerDbm", "transmitGainDbi", "receiveGainDbi", "transmitLossDb",
                "receiveLossDb", "sensitivityDbm", "reserveDb").map { input.d(it) }
            val grid = listOf("radiusMeters", "spacingMeters", "minEastMeters", "maxNorthMeters", "columns", "rows")
                .map { input.getValue(it).jsonPrimitive.long }
            val nodes = input.getValue("nodes").jsonArray.map { it.jsonObject }.map {
                PortableInputFingerprint.Node(it.getValue("sourceID").jsonPrimitive.content, it.getValue("nodeID").jsonPrimitive.content,
                    it.d("latitude"), it.d("longitude"))
            }
            assertEquals(case.getValue("name").jsonPrimitive.content, case.getValue("sha256").jsonPrimitive.content,
                PortableInputFingerprint.coverage(doubles, grid, input.getValue("catalogComplete").jsonPrimitive.boolean, nodes))
        }
    }

    @Test fun coverageAdapterReadsEngineInputsInContractOrder() {
        val case = vectors.getValue("coverageInputs").jsonArray.first().jsonObject
        val input = case.getValue("input").jsonObject
        val grid = CoverageGrid(16093, 1609, -16090, 16090, -16090, 16090)
        assertEquals(listOf(21, 21), listOf(grid.columns, grid.rows))
        val inputs = CoverageStudyInputs(CoverageTerrainCoordinate(input.d("transmitterLatitude"), input.d("transmitterLongitude")), grid,
            CoverageLinkBudget(input.d("transmitPowerDbm"), input.d("transmitGainDbi"), input.d("receiveGainDbi"),
                input.d("transmitLossDb"), input.d("receiveLossDb"), input.d("sensitivityDbm"), input.d("reserveDb")),
            input.d("frequencyMHz"), input.d("transmitHeightMeters"), input.d("receiveHeightMeters"))
        val nodes = input.getValue("nodes").jsonArray.map { it.jsonObject }.map {
            CoverageNodeSnapshot(it.getValue("sourceID").jsonPrimitive.content, it.getValue("nodeID").jsonPrimitive.content, it.d("latitude"), it.d("longitude"))
        }
        assertEquals(case.getValue("sha256").jsonPrimitive.content, PortableInputFingerprint.coverage(inputs, nodes, false))
    }

    @Test fun linkProfileFingerprintsMatchTheReference() {
        val cases = vectors.getValue("linkProfileInputs").jsonArray
        assertEquals(8, cases.size)
        for (case in cases.map { it.jsonObject }) {
            val input = case.getValue("input").jsonObject
            fun endpoint(name: String) = input.getValue(name).jsonObject.let {
                // Names are labels and must not change the fingerprint.
                SavedEndpoint("Any label", it.d("latitude"), it.d("longitude"), SavedAntenna(it.d("heightMeters"), it.d("gainDbi"), it.d("lossDb")))
            }
            val profile = SavedLinkProfile(endpoint("pointA"), endpoint("pointB"), input.d("frequencyMHz"), input.d("transmitPowerDbm"),
                input.d("sensitivityDbm"), input.d("refractionK"), input.getValue("sampleCount").jsonPrimitive.intOrNull)
            assertEquals(case.getValue("name").jsonPrimitive.content, case.getValue("sha256").jsonPrimitive.content,
                PortableInputFingerprint.linkProfile(profile))
            assertEquals(PortableInputFingerprint.linkProfile(profile),
                PortableInputFingerprint.linkProfile(profile.copy(pointA = profile.pointA.copy(name = null))))
        }
    }

    /** The production budget recomputes each stored loss's margin bit for bit, so payloads can store losses only. */
    @Test fun productionBudgetRecomputesMarginsBitForBit() {
        for (case in vectors.getValue("margins").jsonArray.map { it.jsonObject }) {
            val b = case.getValue("budget").jsonObject
            val budget = CoverageLinkBudget(b.d("transmitPowerDbm"), b.d("transmitGainDbi"), b.d("receiveGainDbi"),
                b.d("transmitLossDb"), b.d("receiveLossDb"), b.d("sensitivityDbm"), b.d("reserveDb"))
            val reception = budget.reception(case.d("lossDb"))
            val name = case.getValue("name").jsonPrimitive.content
            assertEquals(name, case.getValue("maximumLossDb").jsonPrimitive.content, budget.maximumLossDb.bits())
            assertEquals(name, case.getValue("adjustedMarginDb").jsonPrimitive.content, reception.adjustedMarginDb.bits())
            assertEquals(name, case.getValue("receiveLevelDbm").jsonPrimitive.content, reception.receiveLevelDbm.bits())
        }
    }

    /** kotlinx.serialization parses the reference text exactly and its own encode/decode keeps every bit. */
    @Test fun jsonNumbersRoundTripBitExactly() {
        for (case in vectors.getValue("jsonNumbers").jsonArray.map { it.jsonObject }) {
            val expected = case.getValue("bits").double()
            val text = case.getValue("text").jsonPrimitive.content
            assertEquals(text, expected.bits(), Json.decodeFromString(Double.serializer(), text).bits())
            val encoded = Json.encodeToString(ListSerializer(Double.serializer()), listOf(expected))
            assertEquals(encoded, expected.bits(), Json.decodeFromString(ListSerializer(Double.serializer()), encoded).single().bits())
        }
    }

    @Test fun nonFiniteInputsAreRefused() {
        assertThrows(IllegalArgumentException::class.java) { PortableInputFingerprint.Writer("x").double(Double.NaN) }
        assertThrows(IllegalArgumentException::class.java) { PortableInputFingerprint.Writer("x").double(Double.POSITIVE_INFINITY) }
    }
}
